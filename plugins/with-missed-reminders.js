// Android: show a reminder that was due while the phone was off.
//
// After a reboot, expo-notifications re-arms its stored requests and drops any
// whose time has passed, so a 07:00 reminder on a phone switched off at 07:00
// never shows. This adds a boot receiver that runs before expo's (higher
// priority; expo does its pass on a background thread). A past owiwi.* request
// still in expo's store never fired, so the latest one due today is handed back
// to expo to present (same channel, icons, sound and tap handling). Delivered
// reminders and a cancelled nudge are no longer stored, so they never repeat.
const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const CLASS_NAME = 'MissedReminderReceiver';
const BOOT_ACTIONS = [
  'android.intent.action.BOOT_COMPLETED',
  'android.intent.action.QUICKBOOT_POWERON',
  'com.htc.intent.action.QUICKBOOT_POWERON',
];

const kotlin = (pkg) => `package ${pkg}

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.util.Log
import expo.modules.notifications.notifications.model.Notification
import expo.modules.notifications.notifications.triggers.DateTrigger
import expo.modules.notifications.service.NotificationsService
import expo.modules.notifications.service.delegates.SharedPreferencesNotificationsStore
import java.util.Calendar

// Generated by plugins/with-missed-reminders.js. Edit the plugin, not this file.
class ${CLASS_NAME} : BroadcastReceiver() {
  override fun onReceive(context: Context, intent: Intent) {
    try {
      val now = System.currentTimeMillis()
      val today = dayKey(now)
      val missed = SharedPreferencesNotificationsStore(context).allNotificationRequests
        .filter { it.identifier.startsWith("owiwi.") }
        .mapNotNull { r -> (r.trigger as? DateTrigger)?.let { r to it.timestamp } }
        .filter { (_, at) -> at <= now && dayKey(at) == today }
        .maxByOrNull { (_, at) -> at }
        ?.first ?: return
      NotificationsService.receive(context, Notification(missed))
    } catch (e: Exception) {
      Log.w("owiwi", "missed reminder check failed: \${e.message}")
    }
  }

  private fun dayKey(millis: Long): Int {
    val c = Calendar.getInstance().apply { timeInMillis = millis }
    return c.get(Calendar.YEAR) * 1000 + c.get(Calendar.DAY_OF_YEAR)
  }
}
`;

function withReceiver(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    const name = `.${CLASS_NAME}`;
    app.receiver = (app.receiver ?? []).filter((r) => r.$['android:name'] !== name);
    app.receiver.push({
      $: { 'android:name': name, 'android:exported': 'true' },
      'intent-filter': [
        {
          $: { 'android:priority': '999' },
          action: BOOT_ACTIONS.map((a) => ({ $: { 'android:name': a } })),
        },
      ],
    });
    return cfg;
  });
}

function withReceiverSource(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('with-missed-reminders: android.package is required');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${CLASS_NAME}.kt`), kotlin(pkg));
      return cfg;
    },
  ]);
}

module.exports = (config) => withReceiverSource(withReceiver(config));
